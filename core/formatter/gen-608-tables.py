"""Generate core/formatter/charset-608-tables.h.

Reads libcaption's UTF-8 -> CEA-608 rules from an OBS source tree, so the
caption formatter only emits characters OBS can encode, and builds the
fallback table that folds other Latin letters to ASCII.

Usage (after a plugin configure has fetched OBS into .deps/):
    python core/formatter/gen-608-tables.py \
        .deps/obs-studio-30.2.3/deps/libcaption/src/eia608_from_utf8.re2c
"""

import re
import sys
import unicodedata
from pathlib import Path

# Letters NFD cannot reduce to one ASCII letter.
SPECIAL = {
    0x00C6: "AE", 0x00E6: "ae", 0x0152: "OE", 0x0153: "oe",
    0x00D0: "D", 0x00F0: "d", 0x00DE: "TH", 0x00FE: "th",
    0x0110: "D", 0x0111: "d", 0x0126: "H", 0x0127: "h",
    0x0131: "i", 0x0141: "L", 0x0142: "l", 0x0166: "T",
    0x0167: "t", 0x0138: "k", 0x0149: "'n", 0x014A: "N",
    0x014B: "n", 0x017F: "s",
}


def read_608_chars(re2c_path):
    text = Path(re2c_path).read_text(encoding="latin-1")
    pattern = r'"((?:\\x[0-9A-F]{2}){2,})"\s*\{'
    chars = []
    for m in re.finditer(pattern, text):
        raw = bytes(int(h, 16) for h in re.findall(r"x([0-9A-F]{2})", m.group(1)))
        chars.append(ord(raw.decode("utf-8")))
    return sorted(set(chars))


def fold_table(extended):
    rows = []
    for cp in range(0x00C0, 0x0250):
        if cp in extended:
            continue
        if cp in SPECIAL:
            rows.append((cp, SPECIAL[cp]))
            continue
        decomposed = unicodedata.normalize("NFD", chr(cp))
        base = "".join(c for c in decomposed if not unicodedata.combining(c))
        if len(base) == 1 and base.isascii() and base.isalpha():
            rows.append((cp, base))
    return rows


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    extended = read_608_chars(sys.argv[1])
    out = [
        "/*",
        " * simple-local-captions",
        " * SPDX-FileCopyrightText: 2026 simple-local-captions contributors",
        " * SPDX-License-Identifier: GPL-2.0-or-later",
        " */",
        "/* Generated by gen-608-tables.py from libcaption's",
        " * eia608_from_utf8.re2c (OBS 30.2.3). Do not edit by hand. */",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "namespace slc::tables {",
        "",
        "/* Non-ASCII characters libcaption encodes, sorted. */",
        "constexpr char32_t extended_608[] = {",
    ]
    for cp in extended:
        out.append(f"\t0x{cp:04X}, /* {unicodedata.name(chr(cp)).lower()} */")
    out += [
        "};",
        "",
        "struct Fold {",
        "\tchar32_t from;",
        "\tconst char *to;",
        "};",
        "",
        "/* Latin letters without a 608 glyph -> ASCII, sorted by from. */",
        "constexpr Fold fold_ascii[] = {",
    ]
    for cp, rep in fold_table(set(extended)):
        name = unicodedata.name(chr(cp)).lower()
        out.append(f'\t{{0x{cp:04X}, "{rep}"}}, /* {name} */')
    out += ["};", "", "} // namespace slc::tables", ""]
    target = Path(__file__).with_name("charset-608-tables.h")
    target.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {target}: {len(extended)} extended, fold table generated")


if __name__ == "__main__":
    main()
